# обезличивание: в системе храним только псевдо-ID пациента и текст без персональных данных
import hashlib                                    # хэш-функция для HMAC
import hmac                                       # HMAC вместо sha256(соль:ID) — стандартная конструкция для ключевого хэша
import os                                         # чтение «соли» из окружения
import re                                         # поиск персональных данных в тексте

_PLACEHOLDERS = {"", "change-me-in-production", "замените-на-секрет"}   # известные заглушки — с ними не стартуем


def _load_salt() -> bytes:
    # соль обязательна и длинная: без неё псевдо-ID можно обратить перебором
    salt = os.environ.get("CM_PSEUDO_SALT", "")   # соль из окружения (.env, не из репозитория)
    if salt in _PLACEHOLDERS or len(salt) < 32:   # заглушка или короткая
        if os.environ.get("CM_ENV", "production") != "demo":   # в демо разрешаем, в бою — нет
            raise RuntimeError("CM_PSEUDO_SALT не задан или слабый (нужно ≥32 символов). Сгенерируйте: "
                               "python -c \"import secrets;print(secrets.token_urlsafe(48))\"")
        salt = "demo-only-salt-not-for-real-patients"   # демо-режим: только синтетика
    return salt.encode()                          # байты для HMAC


SALT = _load_salt()                               # читаем один раз при импорте: сервис без соли не поднимется


def pseudo_id(patient_id: str) -> str:
    # реальный ID пациента из МИС -> псевдо-ID
    if not patient_id or not str(patient_id).strip():   # пустой ID не превращаем в «None»: иначе все такие события стали бы одним пациентом
        raise ValueError("patient_id пустой")      # пусть вызывающий вернёт 400
    return "P-" + hmac.new(SALT, str(patient_id).strip().encode(), hashlib.sha256).hexdigest()


def short(pid: str) -> str:
    # короткая подпись псевдо-ID для экрана (только отображение, не ключ!)
    return pid[:10]                                # «P-1a2b3c4d»


# порядок важен: сначала строки-шапки, затем конкретные форматы
_PATTERNS = [
    # строка-шапка «ФИО: ...» / «Пациент: ...». Без двоеточия строку целиком НЕ стираем:
    # «Пациентка в постменопаузе, эндометрий 12 мм» — это клиника, её терять нельзя
    (re.compile(r"(?im)^\s*(ф\.?\s*и\.?\s*о\.?|пациент(?:ка)?|больн(?:ой|ая))\s*[:\-].*$"), r"\1: [скрыто]"),
    # врач (тоже персональные данные): «Врач: Роман Викторович», в формах МИС — значение на следующей строке
    (re.compile(r"(?im)^(\s*(?:врач|подпись врача|направивший врач|исполнитель)\s*:)[ \t]*\n[^\n]*"), r"\1 [скрыто]"),
    (re.compile(r"(?im)^(\s*(?:врач|подпись врача|направивший врач|исполнитель)\s*:)[ \t]*\S[^\n]*"), r"\1 [скрыто]"),
    (re.compile(r"(?im)^(\s*(?:пациент(?:ка)?|ф\.?\s*и\.?\s*о\.?(?:\s*пациента)?)\s*:)[ \t]*\n(?![^\n]*:)[^\n]+"), r"\1 [скрыто]"),
    # ФИО полностью и имя-отчество: «Широков Роман Викторович», «Наталья Федоровна»
    (re.compile(r"\b(?:[А-ЯЁ][а-яё]+\s+)?[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:вич|вна|ична|чна)\b"), "[ФИО]"),
    # дата рождения словами и на следующей строке: «Дата рождения:\n18 сентября 1981 г.»
    (re.compile(r"(?i)(дата\s+рождения)\s*:?\s*\n?\s*\d{1,2}(?:\s+[а-яё]+\s+|[./])\d{1,2}?[./]?\d{2,4}[ \t]*(?:г\.?)?"), r"\1: [скрыто]"),
    (re.compile(r"\b[А-ЯЁ][а-яё]{2,}(?:ова|ева|ина|ов|ев|ин|ский|ская|ко)\s+[А-ЯЁ]\.(?=\s*[)\n,]|$)"), "[ФИО]"),
    # «Пациентка Петрова А.А.», «Степаненко М.В.», «М.П. Иванова» — фамилия + инициалы в любом месте
    (re.compile(r"\b[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.?"), "[ФИО]"),
    (re.compile(r"\b[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?[А-ЯЁ][а-яё]{2,}"), "[ФИО]"),
    (re.compile(r"(?im)(дата\s+рождения|д\.\s*р\.|г\.\s*р\.)\s*[:\-]?\s*\d{1,2}[./]\d{1,2}[./]\d{2,4}"), r"\1: [скрыто]"),
    (re.compile(r"(?i)(полис|снилс|паспорт|омс|дмс)[^\n]{0,8}?[\d\- ]{8,}"), r"\1 [скрыто]"),
    # телефоны и без +7/8 в начале («916 123 45 67»), в т.ч. со скобками
    (re.compile(r"(?<!\d)(?:(?:\+7|8)[\s\-(]*)?\(?9\d{2}\)?[\s\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"), "[телефон]"),
    (re.compile(r"(?<!\d)(?:\+7|8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"), "[телефон]"),
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+"), "[email]"),
]


def scrub(text: str) -> str:
    # удалить из текста типовые персональные данные
    if not isinstance(text, str):                  # не строка — ошибка 400, а не падение сервиса
        raise ValueError("text должен быть строкой")
    text = text.replace("\xa0", " ")              # неразрывные пробелы из Word ломали шаблоны («Подпись\xa0врача:»)
    for rx, repl in _PATTERNS:                    # каждый шаблон
        text = rx.sub(repl, text)                 # заменяем найденное на заглушку
    return text                                   # обезличенный текст
